/**
 * Builds what SafeImage needs to serve images efficiently:
 *   - a 640px twin (name-640.webp) of every WebP wider than 1000px, so phones
 *     can skip the full-size screenshot
 *   - src/data/imageMeta.js: intrinsic size of every image, used for the
 *     width/height attributes (no layout shift) and to know which have a twin
 *
 * Run after adding or replacing images:  npm run image-variants
 */
import sharp from "sharp";
sharp.cache(false);
import { readdir, writeFile } from "fs/promises";
import { join, relative, dirname, extname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PUBLIC_DIR = join(__dirname, "../public");
const IMAGES_DIR = join(PUBLIC_DIR, "images");
const OUT_FILE = join(__dirname, "../src/data/imageMeta.js");

const TWIN_WIDTH = 640;
const TWIN_THRESHOLD = 1000;
const SKIP_DIRS = new Set(["og"]);
const isTwin = (file) => file.endsWith(`-${TWIN_WIDTH}.webp`);
// The hero illustration and logos have their own sizing (see HeroSection, resize-images.js).
const hasOwnSizes = (file) => /illustration|logo/i.test(file);

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) files.push(...(await walk(full)));
    } else if ([".webp", ".jpg", ".jpeg", ".png"].includes(extname(entry.name).toLowerCase())) {
      files.push(full);
    }
  }
  return files;
}

const files = (await walk(IMAGES_DIR)).filter((file) => !isTwin(file)).sort();
const meta = {};

for (const file of files) {
  const { width, height } = await sharp(file).metadata();
  const url = "/" + relative(PUBLIC_DIR, file).replaceAll("\\", "/");
  const wantsTwin = file.endsWith(".webp") && width > TWIN_THRESHOLD && !hasOwnSizes(file);

  if (wantsTwin) {
    const twin = file.replace(/\.webp$/, `-${TWIN_WIDTH}.webp`);
    await sharp(file).resize({ width: TWIN_WIDTH }).webp({ quality: 80 }).toFile(twin);
  }
  meta[url] = wantsTwin ? [width, height, TWIN_WIDTH] : [width, height];
}

const body = Object.entries(meta)
  .map(([url, value]) => `  ${JSON.stringify(url)}: [${value.join(", ")}],`)
  .join("\n");

await writeFile(
  OUT_FILE,
  `// Generated by scripts/make-image-variants.js. Do not edit by hand.
// url -> [width, height] or [width, height, twinWidth] when a name-<twinWidth>.webp exists.
const imageMeta = {
${body}
};

export default imageMeta;
`
);

console.log(`Wrote ${Object.keys(meta).length} entries to ${relative(join(__dirname, ".."), OUT_FILE)}`);
